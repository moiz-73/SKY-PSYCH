"""Tests for src/telemetry/headpose.py.

Synthetic 2D landmark sets are generated by projecting the canonical 3D face
model through the same approximate camera intrinsics used by the estimator
(``cv2.projectPoints``), so the tests round-trip the PnP pipeline without any
camera or ML dependency.

Owned by: telemetry agent.
"""

import math

import numpy as np
import pytest

from src.telemetry.headpose import (
    CHIN,
    HEAD_MODEL_3D,
    HEAD_MODEL_POINT_IDS,
    LEFT_EYE_OUTER,
    LEFT_MOUTH_CORNER,
    NOSE_TIP,
    RIGHT_EYE_OUTER,
    RIGHT_MOUTH_CORNER,
    HeadDeviationTracker,
    estimate_head_pose,
)

FRAME = (640, 480)


# ---------------------------------------------------------------------------
# Synthetic landmark generation (deterministic, no camera required)
# ---------------------------------------------------------------------------
def _project_head(rvec_deg=(0.0, 0.0, 0.0), tvec_mm=(0.0, 0.0, 600.0)):
    """Project the canonical model into a (478, 2) landmark array."""
    import cv2

    w, h = FRAME
    camera_matrix = np.array(
        [[float(w), 0.0, w / 2.0], [0.0, float(w), h / 2.0], [0.0, 0.0, 1.0]],
        dtype=np.float64,
    )
    dist_coeffs = np.zeros((4, 1), dtype=np.float64)
    rvec = np.array(rvec_deg, dtype=np.float64) * math.pi / 180.0
    tvec = np.array(tvec_mm, dtype=np.float64)
    points_2d, _ = cv2.projectPoints(HEAD_MODEL_3D, rvec, tvec, camera_matrix, dist_coeffs)
    points_2d = points_2d.reshape(-1, 2)

    landmarks = np.zeros((478, 2), dtype=np.float64)
    for idx, point in zip(HEAD_MODEL_POINT_IDS, points_2d):
        landmarks[idx, 0] = point[0]
        landmarks[idx, 1] = point[1]
    return landmarks


def _assert_finite_or_none(angles):
    """Angles must be a (None, None, None) triple or three finite floats."""
    if angles[0] is None:
        assert angles == (None, None, None)
    else:
        for angle in angles:
            assert angle is not None
            assert math.isfinite(angle)


# ---------------------------------------------------------------------------
# Neutral face -> pitch/yaw near zero
# ---------------------------------------------------------------------------
def test_neutral_face_pitch_yaw_near_zero():
    landmarks = _project_head(rvec_deg=(0.0, 0.0, 0.0), tvec_mm=(0.0, 0.0, 600.0))
    pitch, yaw, roll = estimate_head_pose(landmarks, *FRAME)
    _assert_finite_or_none((pitch, yaw, roll))
    assert pitch is not None
    assert abs(pitch) < 1.0
    assert abs(yaw) < 1.0
    assert abs(roll) < 1.0


def test_neutral_face_accepts_python_list():
    landmarks = _project_head(rvec_deg=(0.0, 0.0, 0.0)).tolist()
    pitch, yaw, roll = estimate_head_pose(landmarks, *FRAME)
    assert pitch is not None
    assert abs(pitch) < 1.0
    assert abs(yaw) < 1.0


# ---------------------------------------------------------------------------
# Large horizontal displacement -> non-zero yaw / head-off
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("yaw_deg", [40.0, -40.0])
def test_turned_head_produces_nonzero_yaw(yaw_deg):
    # A turned head displaces the facial features horizontally; the estimator
    # must recover a clearly non-zero yaw beyond the default 25 deg limit.
    landmarks = _project_head(rvec_deg=(0.0, yaw_deg, 0.0), tvec_mm=(0.0, 0.0, 600.0))
    pitch, yaw, roll = estimate_head_pose(landmarks, *FRAME)
    _assert_finite_or_none((pitch, yaw, roll))
    assert yaw is not None
    assert abs(yaw) > 25.0  # beyond HeadDeviationTracker default yaw limit
    assert 30.0 < abs(yaw) < 50.0  # close to the injected 40 deg

    # Feeding the recovered pose to the tracker must trigger HEAD_OFF (~1.0).
    tracker = HeadDeviationTracker()
    for i in range(5):
        tracker.update(pitch, yaw, float(i * 10))
    assert tracker.value() == pytest.approx(1.0, abs=0.05)


def test_large_horizontal_translation_stays_neutral():
    # Pure image-space displacement is absorbed by the translation vector and
    # must NOT fabricate a yaw (physically correct behaviour).
    landmarks = _project_head(rvec_deg=(0.0, 0.0, 0.0), tvec_mm=(200.0, 0.0, 600.0))
    pitch, yaw, roll = estimate_head_pose(landmarks, *FRAME)
    _assert_finite_or_none((pitch, yaw, roll))
    assert yaw is not None
    assert abs(yaw) < 1.0


def test_pitch_recovered():
    landmarks = _project_head(rvec_deg=(25.0, 0.0, 0.0), tvec_mm=(0.0, 0.0, 600.0))
    pitch, yaw, roll = estimate_head_pose(landmarks, *FRAME)
    _assert_finite_or_none((pitch, yaw, roll))
    assert pitch is not None
    assert abs(pitch) > 15.0
    assert 20.0 < abs(pitch) < 30.0


# ---------------------------------------------------------------------------
# Failure handling -> (None, None, None), never fake normal values
# ---------------------------------------------------------------------------
def test_none_landmarks_returns_none():
    assert estimate_head_pose(None, *FRAME) == (None, None, None)


def test_missing_landmark_indices_returns_none():
    small = np.zeros((10, 2), dtype=np.float64)  # lacks index 152 etc.
    assert estimate_head_pose(small, *FRAME) == (None, None, None)


def test_malformed_shape_returns_none():
    flat = np.zeros((478,), dtype=np.float64)
    assert estimate_head_pose(flat, *FRAME) == (None, None, None)


def test_degenerate_identical_points_returns_none():
    # All six key points identical: cv2.solvePnP raises/fails internally and
    # the module must degrade to None instead of crashing or faking normal.
    landmarks = np.zeros((478, 2), dtype=np.float64)
    for idx in HEAD_MODEL_POINT_IDS:
        landmarks[idx] = (320.0, 240.0)
    assert estimate_head_pose(landmarks, *FRAME) == (None, None, None)


def test_nan_landmarks_returns_none():
    landmarks = _project_head()
    landmarks[NOSE_TIP] = (float("nan"), float("nan"))
    assert estimate_head_pose(landmarks, *FRAME) == (None, None, None)


def test_out_of_bounds_landmarks_returns_none():
    landmarks = _project_head()
    landmarks[CHIN] = (1.0e9, 1.0e9)
    assert estimate_head_pose(landmarks, *FRAME) == (None, None, None)


def test_invalid_frame_size_returns_none():
    landmarks = _project_head()
    assert estimate_head_pose(landmarks, 0, 480) == (None, None, None)
    assert estimate_head_pose(landmarks, 640, -1) == (None, None, None)


# ---------------------------------------------------------------------------
# NaNs are never produced
# ---------------------------------------------------------------------------
@pytest.mark.parametrize(
    "rvec_deg",
    [
        (0.0, 0.0, 0.0),
        (15.0, 0.0, 0.0),
        (0.0, 30.0, 0.0),
        (0.0, 0.0, 20.0),
        (10.0, -20.0, 5.0),
        (-30.0, 40.0, -10.0),
    ],
)
def test_no_nans_produced(rvec_deg):
    landmarks = _project_head(rvec_deg=rvec_deg, tvec_mm=(0.0, 0.0, 500.0))
    angles = estimate_head_pose(landmarks, *FRAME)
    _assert_finite_or_none(angles)
    if angles[0] is not None:
        assert not any(math.isnan(a) for a in angles)


